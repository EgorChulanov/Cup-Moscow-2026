def cell_h(body, w, size):
    """Оценка высоты текста в ячейке: Miro переносит по ширине, кириллица около 0,55 em на символ."""
    import math
    lines = 0
    for part in body.split("\n"):
        lines += max(1, math.ceil(len(part) * size * 0.6 / max(w - 56, 50)))
    return int(lines * size * 1.55 + 64)


def table(x, y, widths, rows, size=24, head=True, first_bold=True, fills=None):
    """Таблица из фигур с текстом. Возвращает (элементы, высота). Первая строка шапка, первый столбец жирный."""
    items, cy = [], y
    for ri, row in enumerate(rows):
        h = max(cell_h(c, w, size) for c, w in zip(row, widths))
        cx = x
        for ci, (c, w) in enumerate(zip(row, widths)):
            is_head = head and ri == 0
            fill = "#ffdd2d" if is_head else (fills[ri] if fills and fills[ri] else (G if ci == 0 and first_bold else GR))
            items.append(rect(cx, cy, w, h, c.replace("\n", "<br/>"), fill, size, is_head or (ci == 0 and first_bold),
                              "left", "top", "#e7e7e7" if not is_head else "#ffdd2d", rx=8))
            cx += w + 8
        cy += h + 8
    return items, cy - y


def banner(x, y, w, body, size=34, fill=Y, stroke=YS):
    h = cell_h(body, w, size) + 16
    return [rect(x, y, w, h, body, fill, size, True, "left", "middle", stroke, rx=12)], h


